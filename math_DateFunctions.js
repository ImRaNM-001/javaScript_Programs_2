// part 2- all about Date methods
const todayDate = new Date();           // new Date() constructor function is called which prints today's date
console.log(todayDate);                 // prints today's date in the format:  2020-01-26T19:40:26.955Z

console.log(todayDate.getDate() );      // prints today's date only like 27/Jan, it will print 27
console.log(todayDate.getFullYear() );          // prints current year 2020
console.log(todayDate.toDateString() );         // prints Mon Jan 27 2020
console.log(todayDate.toTimeString() );         // prints 01:29:31 GMT+0530 (India Standard Time)

